# **Importing the Essential Libraries**
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

# **Importing the dataset from the local storage**
data=pd.read_csv("C:\\Users\\MHA\\Desktop\\sales_dataset.csv")
print(data)

# **1. Data Inspection and Preprocessing**
# Before building the dashboard, let's inspect the data types, check for missing values, and format the `order_date` column correctly so we can plot time-series trends.

# Convert order_date to datetime
data['order_date'] = pd.to_datetime(data['order_date'])

# Display basic info and check for null values
print("--- Dataset Info ---")
print(data.info())

print("\n--- Summary Statistics ---")
print(data.describe())

# **2. Key Performance Indicators (KPIs)**
# Let's calculate the high-level metrics of your sales business.

total_revenue = data['revenue'].sum()
total_quantity = data['quantity'].sum()
avg_rating = data['customer_rating'].mean()
avg_discount = data['discount'].mean() * 100

print(f"=========================================")
print(f"         SALES PERFORMANCE KPIs          ")
print(f"=========================================")
print(f" Total Revenue:       ${total_revenue:,.2f}")
print(f" Total Units Sold:    {total_quantity:,}")
print(f" Average Rating:      {avg_rating:.2f} / 5.0")
print(f" Average Discount:    {avg_discount:.1f}%")
print(f"=========================================")

# **3. Dashboard Visualizations using Matplotlib & Seaborn**
# These charts provide business-focused insights into revenue trends, category performance,
# regional market share, and payment behavior without using Plotly.

sns.set_style('whitegrid')


def plot_revenue_trends(ax, df: pd.DataFrame):
    """Creates a line chart showing daily revenue performance over time."""
    daily_data = df.groupby('order_date', as_index=False)['revenue'].sum()
    sns.lineplot(data=daily_data, x='order_date', y='revenue', ax=ax, color='#1f77b4', linewidth=2.5)
    ax.set_title('Daily Revenue Performance', fontsize=14, fontweight='bold')
    ax.set_xlabel('Date')
    ax.set_ylabel('Revenue ($)')
    ax.tick_params(axis='x', rotation=45)


def plot_category_performance(ax, df: pd.DataFrame):
    """Shows which product categories contribute the most revenue."""
    cat_data = df.groupby('product_category', as_index=False)['revenue'].sum().sort_values('revenue', ascending=False)
    sns.barplot(data=cat_data, x='revenue', y='product_category', hue='product_category', palette='Blues_d', dodge=False, legend=False, ax=ax)
    ax.set_title('Revenue Contribution by Product Category', fontsize=14, fontweight='bold')
    ax.set_xlabel('Revenue ($)')
    ax.set_ylabel('Product Category')
    for container in ax.containers:
        ax.bar_label(container, fmt='%.0f', padding=3)


def plot_regional_distribution(ax, df: pd.DataFrame):
    """Displays the share of total revenue by region using a donut chart."""
    region_data = df.groupby('region', as_index=False)['revenue'].sum()
    colors = sns.color_palette('Set2', n_colors=len(region_data))
    ax.pie(
        region_data['revenue'],
        labels=region_data['region'],
        autopct='%1.1f%%',
        startangle=90,
        colors=colors,
        wedgeprops={'edgecolor': 'white', 'linewidth': 1.2}
    )
    ax.set_title('Regional Revenue Share', fontsize=14, fontweight='bold')
    ax.axis('equal')


def plot_payment_breakdown(ax, df: pd.DataFrame):
    """Compares revenue generated by payment method across product categories."""
    payment_data = df.groupby(['payment_method', 'product_category'], as_index=False)['revenue'].sum()
    sns.barplot(
        data=payment_data,
        x='payment_method',
        y='revenue',
        hue='product_category',
        palette='Set2',
        ax=ax
    )
    ax.set_title('Revenue by Payment Method and Product Category', fontsize=14, fontweight='bold')
    ax.set_xlabel('Payment Method')
    ax.set_ylabel('Revenue ($)')
    ax.legend(title='Product Category', bbox_to_anchor=(1.02, 1), loc='upper left')


# Build a single dashboard and keep it open until the user closes it
fig, axes = plt.subplots(2, 2, figsize=(18, 12))
plot_revenue_trends(axes[0, 0], data)
plot_category_performance(axes[0, 1], data)
plot_regional_distribution(axes[1, 0], data)
plot_payment_breakdown(axes[1, 1], data)

fig.tight_layout()
plt.show(block=True)


